function initializeFAQ() {
  const faqQuestions = document.querySelectorAll(".faq-question");

  faqQuestions.forEach(question => {
    question.addEventListener("click", () => {
      const answer = question.nextElementSibling;
      const plus = question.querySelector(".faq-plus");
      const isOpen = answer.style.maxHeight;

      document.querySelectorAll(".faq-answer").forEach(item => {
        item.style.maxHeight = null;
      });

      document.querySelectorAll(".faq-plus").forEach(item => {
        item.textContent = "+";
      });

      if (!isOpen) {
        answer.style.maxHeight = answer.scrollHeight + "px";
        if (plus) plus.textContent = "−";
      }
    });
  });
}

initializeFAQ();

/* =========================================================
   SMOOTH ANCHOR SCROLLING
========================================================= */

document.querySelectorAll('a[href^="#"]').forEach(link => {
  link.addEventListener("click", event => {
    const targetId = link.getAttribute("href");
    if (targetId === "#") return;

    const target = document.querySelector(targetId);
    if (!target) return;

    event.preventDefault();
    const navHeight = 72;
    const targetPosition = target.getBoundingClientRect().top + window.scrollY - navHeight;

    window.scrollTo({
      top: targetPosition,
      behavior: "smooth"
    });
  });
});

/* =========================================================
   CINEMATIC CURSOR GLOW & MOUSE PARALLAX
========================================================= */

const hero = document.querySelector(".hero");
const mockup = document.querySelector(".mockup");
const heroGlow = document.getElementById("hero-glow");

if (hero) {
  hero.addEventListener("mousemove", event => {
    const rect = hero.getBoundingClientRect();
    const x = event.clientX - rect.left;
    const y = event.clientY - rect.top;

    if (heroGlow) {
      heroGlow.style.left = `${x}px`;
      heroGlow.style.top = `${y}px`;
      heroGlow.style.opacity = "1";
    }

    if (mockup) {
      const offsetX = (x / rect.width - 0.5) * 6;
      const offsetY = (y / rect.height - 0.5) * -6;
      mockup.style.transform = `perspective(1000px) rotateY(${offsetX}deg) rotateX(${offsetY}deg)`;
    }
  });

  hero.addEventListener("mouseleave", () => {
    if (heroGlow) heroGlow.style.opacity = "0";
    if (mockup) mockup.style.transform = "perspective(1000px) rotateY(0deg) rotateX(0deg)";
  });
}

