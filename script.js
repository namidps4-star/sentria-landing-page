/* =========================================================
   LANGUAGE SYSTEM
========================================================= */

let currentLanguage =
  localStorage.getItem("sentria-language") ||
  (navigator.language && navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en");

function normalizeText(text) {
  return text.replace(/\s+/g, " ").trim();
}

function getTranslationMap(language) {
  if (language === "en") {
    const map = {};
    Object.entries(translations.fr).forEach(([english, french]) => {
      map[french] = english;
    });
    return map;
  }
  return translations.fr;
}

function translatePage(language) {
  const map = getTranslationMap(language);
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];

  while (walker.nextNode()) {
    nodes.push(walker.currentNode);
  }

  nodes.forEach(node => {
    const normalized = normalizeText(node.nodeValue);
    if (!normalized) return;

    if (map[normalized]) {
      const original = node.nodeValue;
      const leading = original.match(/^\s*/)?.[0] || "";
      const trailing = original.match(/\s*$/)?.[0] || "";
      node.nodeValue = leading + map[normalized] + trailing;
    }
  });

  if (language === "fr") {
    document.documentElement.lang = "fr";
    document.title = "SentrIA : Voyez le blocage avant qu'il n'arrive";
    document.querySelector('meta[name="description"]')?.setAttribute(
      "content",
      "SentrIA transforme vos données opérationnelles en signaux clairs, priorités claires et décisions concrètes avant que les blocages ne deviennent des incidents."
    );
  } else {
    document.documentElement.lang = "en";
    document.title = "SentrIA: See the bottleneck before it happens";
    document.querySelector('meta[name="description"]')?.setAttribute(
      "content",
      "SentrIA turns your operational data into clear signals, clear priorities, and concrete decisions before bottlenecks become incidents."
    );
  }

  document.querySelectorAll(".lang-switch button").forEach(button => {
    const active = button.dataset.lang === language;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });

  localStorage.setItem("sentria-language", language);

  renderSector(
    document.querySelector(".sector-tab.active")?.dataset.sector || "industry",
    false
  );
}

document.querySelectorAll(".lang-switch button").forEach(button => {
  button.addEventListener("click", () => {
    const language = button.dataset.lang;
    if (language === currentLanguage) return;
    currentLanguage = language;
    translatePage(language);
  });
});

