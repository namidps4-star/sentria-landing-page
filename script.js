const quickfitPills = document.querySelectorAll("#quickfit-pills .quickfit-pill");
const fitCards = document.querySelectorAll(".fit-card");

function activateFit(key, shouldScroll) {
  fitTabs.forEach(item => {
    item.classList.toggle("active", item.dataset.fit === key);
  });

  quickfitPills.forEach(item => {
    item.classList.toggle("active", item.dataset.fit === key);
  });

  fitCards.forEach(card => {
    card.classList.toggle("is-active", card.dataset.fit === key);
  });

  if (shouldScroll) {
    const matchingCard = document.querySelector(`.fit-card[data-fit="${key}"]`);
    if (matchingCard) {
      matchingCard.scrollIntoView({ behavior: "smooth", block: "center" });
    }
  }
}

fitTabs.forEach(tab => {
  tab.addEventListener("click", () => activateFit(tab.dataset.fit, false));
});

quickfitPills.forEach(pill => {
  pill.addEventListener("click", () => activateFit(pill.dataset.fit, true));
});

