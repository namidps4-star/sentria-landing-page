function simulateLiveMetrics() {
  const risksElem = document.getElementById("hero-risks");
  const priorityElem = document.getElementById("hero-priority");
  const bars = document.querySelectorAll(".bars .bar");

  setInterval(() => {
    if (risksElem && Math.random() > 0.6) {
      const current = parseInt(risksElem.textContent, 10);
      const next = Math.max(3, Math.min(12, current + (Math.random() > 0.5 ? 1 : -1)));
      risksElem.textContent = next < 10 ? `0${next}` : next;
    }

    if (priorityElem && Math.random() > 0.7) {
      const val = Math.floor(88 + Math.random() * 8);
      priorityElem.textContent = `${val}%`;
    }

    if (bars.length > 0 && Math.random() > 0.5) {
      const randomBar = bars[Math.floor(Math.random() * (bars.length - 1))];
      const randomHeight = Math.floor(35 + Math.random() * 55);
      randomBar.style.height = `${randomHeight}%`;
    }
  }, 3000);
}

simulateLiveMetrics();

